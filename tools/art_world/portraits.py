('bun','hairpin','cool','silver',.98,.95,'#7b8788','glasses elder shawl'),
('swept','clip','peach','oil',.97,1.03,'#719b99','medic'),
('crop','beanie','cedar','grey',1.13,1.00,'#6b8091','beard fisher'),
