    if 'medic' in features:
        P([(15,54),(21,52),(29,61),(31,66),(26,64)],'#bfd1bb');ln([(40,52),(37,58),(30,65)],'#b4c9b5',2)
        rect(42,59,8,6,'#b7c8b3');rect(45,60,2,4,'#5a867c');rect(44,61,4,2,'#5a867c')
