"""Tight, hand-clustered 3/4 dialogue portraits. Two lip shapes per character."""
from paint import *
I='#182b38'
SKINS={
    'honey':('#9c6852','#bf8966','#dfaa7e','#f1c595'),
    'umber':('#805843','#a77556','#c58e68','#deb387'),
    'cedar':('#704e45','#955f4b','#b87f5f','#d29e74'),
    'peach':('#a56d60','#c88e76','#e2ad8c','#f0c7a1'),
    'cool':('#916e65','#b78e7c','#d5aa94','#e9cbb1'),
}
