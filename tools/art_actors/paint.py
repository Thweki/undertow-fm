def knee(hip, ankle, bend, strength, kick=False):
    mx,my=mid(hip,ankle,.52)
    dx,dy=ankle[0]-hip[0],ankle[1]-hip[1]
    distance=max(1,hypot(dx,dy))
    # The two links compress on a planted foot when the pelvis lowers.
    joint=min(11,sqrt(max(8,(15*strength)**2-(distance*.48)**2)))
    if kick:
        return (mx+5, my-min(11,max(2,(hip[1]-ankle[1])*.4+7)))
    return mx+dy/distance*joint*bend, my-dx/distance*joint*bend

