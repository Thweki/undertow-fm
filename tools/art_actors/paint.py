def make_frame(actor,action,i):
    u=uniforms[actor]
    a=pose(action,i,actor)
    if actor in ('skater','tech') and action=='heavy':
        # Their armed heavy uses a high swing with a planted lunge.
        a.nf=(-12,0);a.ff=(13,0);a.kick=False
        a.lean=[0,-3,-5,-2,4,5,3,2][i]
        a.ne=[(-4,9),(-9,1),(-9,-5),(-1,-10),(12,0),(14,8),(6,9),(-5,12)][i]
        a.nw=[(7,1),(-9,-9),(-12,-16),(-1,-21),(24,-5),(26,10),(15,8),(7,6)][i]
    im=Image.new('RGBA',(96,88))
    p=Plate(im)
    hip=(46+a.dx,u.hip+a.dy)
    shoulder=(hip[0]+a.lean,hip[1]-u.spine+2)
    front=(shoulder[0]-4*u.width,shoulder[1]+1)
    rear=(shoulder[0]+5*u.width,shoulder[1])
    far_leg=((hip[0]+3,hip[1]+1),(47+a.ff[0],77+a.ff[1]))
    near_leg=((hip[0]-3,hip[1]+1),(47+a.nf[0],77+a.nf[1]))
    neck=(shoulder[0]+1,shoulder[1]-4)
    head=(neck[0]+1,neck[1]-7+a.head)
    def draw_arm(anchor,e,w,far):
        elbow=(anchor[0]+e[0]*u.limb**.35,anchor[1]+e[1]*u.limb**.35)
        gauntlet_scale={'brute':1.42,'boss':1.26,'guard':1.10}.get(actor,1)
        spread=8 if action=='skill' and 3<=i<=7 and actor not in ('tech','skater') else 5
        reach=94-round(spread*gauntlet_scale)
        hand=(min(reach,anchor[0]+w[0]*u.limb**.2),anchor[1]+w[1]*u.limb**.2)
        arm(p,actor,anchor,elbow,hand,far,action,i)
    scarf(p,neck,a.wind,actor)
    draw_arm(rear,a.fe,a.fw,True)
    leg(p,actor,*far_leg,True,False)
    if actor=='boss':
        coat(p,actor,hip,a.lean,a.wind)
    leg(p,actor,*near_leg,False,a.kick)
    body(p,actor,hip,a.lean)
    cranium(p,actor,head,a.lean/65,a.wind)
    draw_arm(front,a.ne,a.nw,False)
    if action=='down' and i>0:
        # Pivot the figure through distinct air/contact/rebound poses, preserving hard pixels.
        angle=[0,22,49,78,91,90][i]
        fallen=im.rotate(angle,Image.Resampling.NEAREST,expand=True)
        fallen=fallen.crop(fallen.getbbox())
        im=Image.new('RGBA',(96,88))
        floor=[80,74,70,80,78,80][i]
        im.alpha_composite(fallen,((96-fallen.width)//2,floor-fallen.height))
    return im

COUNTS={'idle':6,'walk':8,'jab':6,'heavy':8,'skill':10,'dodge':6,'hurt':4,'down':6}

def main():
    DEST.mkdir(parents=True,exist_ok=True)
    preview=Image.new('RGB',(96*len(uniforms),88*5),'#34394b')
    for col,actor in enumerate(uniforms):
        moves = dict(COUNTS)
        if actor in ('hero','past'): moves.update(cross=6,upper=6)
        if actor=='hero': moves.update(leap=6)
        for action,count in moves.items():
            strip=Image.new('RGBA',(96*count,88))
            for i in range(count):
                frame=make_frame(actor,action,i)
                box=frame.getbbox()
                assert box and min(box[:2])>0 and box[2]<96 and box[3]<88,(actor,action,i,box)
                strip.alpha_composite(frame,(i*96,0))
                select={'idle':0,'jab':3,'heavy':4,'skill':5,'down':5}
                if i==select.get(action):
                    preview.paste(frame,(col*96,list(select).index(action)*88),frame)
            strip.save(DEST/(actor+'_'+action+'.png'),optimize=True)
    preview.resize((preview.width*2,preview.height*2),Image.Resampling.NEAREST).save(HERE/'cast.png')

if __name__=='__main__':
    main()
