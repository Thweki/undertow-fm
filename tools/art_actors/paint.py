class Plate:
    def __init__(self, image):
        self.im = image
        self.d = ImageDraw.Draw(image)
    @staticmethod
    def px(pt):
        return tuple(round(c) for c in pt)
    def poly(self, color, pts):
        self.d.polygon([self.px(p) for p in pts], fill=color)
    def line(self, color, pts, width=1):
        self.d.line([self.px(p) for p in pts], fill=color, width=width)
    def dot(self, color, x, y):
        self.d.point((round(x),round(y)),fill=color)

class Local:
    def __init__(self, plate, transform):
        self.p = plate
        self.t = transform
    def poly(self, color, pts):
        self.p.poly(color,[self.t(*p) for p in pts])
    def line(self, color, pts, width=1):
        self.p.line(color,[self.t(*p) for p in pts],width)
    def dot(self, color, x, y):
        self.p.dot(color,*self.t(x,y))
    def box(self,color,x,y,w,h):
        self.poly(color,[(x,y),(x+w-1,y),(x+w-1,y+h-1),(x,y+h-1)])

def local(p, centre, sx=1, sy=1, lean=0):
    return Local(p,lambda x,y: (centre[0]+x*sx-y*lean,centre[1]+y*sy))

def mid(a,b,t):
    return (a[0]+(b[0]-a[0])*t,a[1]+(b[1]-a[1])*t)

def along(p,a,b):
    dx,dy=b[0]-a[0],b[1]-a[1]
    length=max(1,hypot(dx,dy))
    # Keep upper / left-facing planes lit during the entire rotation.
    nx,ny=dy/length,-dx/length
    if nx*.42+ny<0:
        nx,ny=-nx,-ny
    return Local(p, lambda t,n: (a[0]+dx*t+nx*n,a[1]+dy*t+ny*n))

